  /// Returns the translation for [key] in [langCode].
  /// Falls back to English if the key or language is missing.
  static String tr(String key, String langCode) {
    final entry = _strings[key];
    if (entry == null) return key;
    return entry[langCode] ?? entry['en'] ?? key;
  }

  /// Translates a crop name (given in English) to [langCode].
  /// E.g. trCrop('Tomato', 'hi') → 'टमाटर'
  static String trCrop(String cropNameEn, String langCode) {
    final key = 'crop_${cropNameEn.toLowerCase()}';
    final entry = _strings[key];
    if (entry == null) return cropNameEn;
    return entry[langCode] ?? entry['en'] ?? cropNameEn;
  }
